function cleanBrandForLetter(raw: string): string {
  return raw
    .replace(/\s*\(Line\s*\d+\)/gi, "")
    .replace(/\s*\(Official CS Line\)/gi, "")
    .replace(/\s*\(Seed:.*?\)/gi, "")
    .replace(/\s*\(Inviz\s*Purwokerto\)/gi, " Purwokerto")
    .replace(/\s*\(Toko Grosir Kaos & Daster\)/gi, "")
    .replace(/\s*\(Gudang Kosmetik Purbalingga\)/gi, "")
    .replace(/\s*\(House of Elena\)/gi, "")
    .replace(/\s*\/\s*Retail/gi, "")
    .replace(/^GKP\s*-\s*/gi, "")
    .trim();
}

